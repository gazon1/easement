use std::collections::BTreeSet;
use std::path::Path;

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

use crate::check::{Key, Violation};

const HEADER: &str = "# Legalized architecture violations. Generated by `easement baseline`.\n\
# Fix them and regenerate: the gate fails on new violations and on stale entries.\n";

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct Baseline {
    pub violations: BTreeSet<Key>,
}

impl Baseline {
    pub fn load(path: &Path) -> Result<Option<Self>> {
        if !path.exists() {
            return Ok(None);
        }
        let text = std::fs::read_to_string(path)
            .with_context(|| format!("cannot read baseline {}", path.display()))?;
        Self::parse(&text)
            .with_context(|| format!("invalid baseline {}", path.display()))
            .map(Some)
    }

    /// The baseline at `path`, relative to `root`, as it was at the Git
    /// revision `rev`; none when the revision has no such file.
    pub fn load_at(root: &Path, path: &Path, rev: &str) -> Result<Option<Self>> {
        // `./` makes the path relative to `root`, not to the top of the repository.
        let spec = format!("{rev}:./{}", crate::scan::slash(path));
        if crate::diff::git(root, &["cat-file", "-e", &spec]).is_err() {
            return Ok(None);
        }
        let text = crate::diff::git(root, &["show", &spec])?;
        Self::parse(&text)
            .with_context(|| format!("invalid baseline {} at {rev}", path.display()))
            .map(Some)
    }

    /// The baseline in `text`, as a baseline file holds it.
    pub fn parse(text: &str) -> Result<Self> {
        let baseline: Self = serde_norway::from_str(text)?;
        // Entries written before keys were canonical still match.
        Ok(Self {
            violations: baseline
                .violations
                .into_iter()
                .map(Key::canonical)
                .collect(),
        })
    }

    pub fn from_violations(violations: &[Violation]) -> Self {
        Self {
            violations: violations.iter().map(Violation::key).collect(),
        }
    }

    /// Splits the violations that `easement baseline` finds over this
    /// baseline into those it may record and the new ones it may not: the
    /// baseline only shrinks unless `accept_new` legalizes new debt.
    pub fn admit(
        &self,
        violations: Vec<Violation>,
        accept_new: bool,
    ) -> (Vec<Violation>, Vec<Violation>) {
        violations
            .into_iter()
            .partition(|v| accept_new || self.violations.contains(&v.key()))
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        let body = serde_norway::to_string(self)?;
        std::fs::write(path, format!("{HEADER}{body}"))
            .with_context(|| format!("cannot write baseline {}", path.display()))
    }
}

/// Result of judging the current violations against a baseline.
pub struct Verdict {
    /// Violations not covered by the baseline.
    pub new: Vec<Violation>,
    /// Violations of the rules in `warn`: reported, never failing.
    pub warnings: Vec<Violation>,
    /// The owner of each component that names one, to ask about a violation by its `from`.
    pub owners: std::collections::BTreeMap<String, String>,
    /// Baseline entries that no longer occur: the debt was paid, the baseline must shrink.
    pub stale: Vec<Key>,
    pub legalized: usize,
}

impl Verdict {
    /// `violations` are the ones being judged (all of them, or only those in a
    /// diff); `current` are the keys of every violation in the project, which
    /// decide whether a baseline entry is stale.
    pub fn judge(
        violations: Vec<Violation>,
        warnings: Vec<Violation>,
        current: &BTreeSet<Key>,
        baseline: Option<&Baseline>,
    ) -> Self {
        let Some(baseline) = baseline else {
            return Self {
                new: violations,
                warnings,
                owners: Default::default(),
                stale: Vec::new(),
                legalized: 0,
            };
        };
        let stale = baseline.violations.difference(current).cloned().collect();
        let (legal, new): (Vec<_>, Vec<_>) = violations
            .into_iter()
            .partition(|v| !v.rule.is_config_rule() && baseline.violations.contains(&v.key()));
        Self {
            new,
            warnings,
            owners: Default::default(),
            stale,
            legalized: legal.len(),
        }
    }

    /// Every reported violation with its level: `error` for the ones that
    /// fail, then `warning` for the rules in `warn`.
    pub fn reported(&self) -> impl Iterator<Item = (&'static str, &Violation)> {
        std::iter::repeat("error")
            .zip(&self.new)
            .chain(std::iter::repeat("warning").zip(&self.warnings))
    }

    /// Who to ask about `v`: the owner of its `from`, or of each component of
    /// a cycle (`from` is `a,b`).
    pub fn owner_of(&self, v: &Violation) -> Option<String> {
        let owners: Vec<&str> = v
            .from
            .split(',')
            .filter_map(|c| self.owners.get(c).map(String::as_str))
            .collect::<std::collections::BTreeSet<_>>()
            .into_iter()
            .collect();
        (!owners.is_empty()).then(|| owners.join(", "))
    }

    pub fn sort(&mut self) {
        for list in [&mut self.new, &mut self.warnings] {
            list.sort_by(|a, b| (&a.file, a.line, a.rule).cmp(&(&b.file, b.line, b.rule)));
        }
    }

    pub fn passed(&self) -> bool {
        self.new.is_empty() && self.stale.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn v(file: &str, to: &str) -> Violation {
        Violation {
            rule: crate::check::RuleId::Dependency,
            file: file.into(),
            line: 1,
            message: String::new(),
            because: None,
            from: "a".into(),
            to: to.into(),
            target: format!("{to}/x"),
            specifier: String::new(),
            evidence: Vec::new(),
        }
    }

    #[test]
    fn one_baseline_entry_legalizes_every_use_of_its_key() {
        let mut second = v("f1", "b");
        second.line = 9;
        let baseline = Baseline::from_violations(&[v("f1", "b")]);
        let found = vec![v("f1", "b"), second];
        let current = found.iter().map(Violation::key).collect();
        let verdict = Verdict::judge(found, Vec::new(), &current, Some(&baseline));
        assert_eq!(verdict.legalized, 2);
        assert!(verdict.passed());
    }

    #[test]
    fn a_baseline_admits_only_the_debt_it_holds() {
        let baseline = Baseline::from_violations(&[v("f1", "b"), v("f2", "b")]);
        let (kept, refused) = baseline.admit(vec![v("f1", "b"), v("f3", "c")], false);
        assert_eq!(kept.len(), 1);
        assert_eq!(kept[0].file, "f1");
        assert_eq!(refused.len(), 1);
        assert_eq!(refused[0].file, "f3");
        let (kept, refused) = baseline.admit(vec![v("f1", "b"), v("f3", "c")], true);
        assert_eq!((kept.len(), refused.len()), (2, 0));
    }

    #[test]
    fn an_old_cycle_entry_with_a_file_still_matches() {
        let dir = tempfile::TempDir::new().unwrap();
        let path = dir.path().join("easement.baseline.yml");
        std::fs::write(
            &path,
            "violations:\n- rule: cycle\n  file: src/a/Z.kt\n  target: ''\n  from: a,b\n  to: ''\n",
        )
        .unwrap();
        let baseline = Baseline::load(&path).unwrap().unwrap();
        let mut cycle = v("src/a/A.kt", "");
        cycle.rule = crate::check::RuleId::Cycle;
        cycle.from = "a,b".into();
        cycle.target = String::new();
        assert!(baseline.violations.contains(&cycle.key()));
    }

    #[test]
    fn ratchet_fails_on_new_and_stale() {
        let baseline = Baseline::from_violations(&[v("f1", "b"), v("f2", "b")]);
        let found = vec![v("f1", "b"), v("f3", "c")];
        let current = found.iter().map(Violation::key).collect();
        let verdict = Verdict::judge(found, Vec::new(), &current, Some(&baseline));
        assert_eq!(verdict.legalized, 1);
        assert_eq!(verdict.new.len(), 1);
        assert_eq!(verdict.new[0].file, "f3");
        assert_eq!(verdict.stale.len(), 1);
        assert_eq!(verdict.stale[0].file, "f2");
        assert!(!verdict.passed());
    }
}
